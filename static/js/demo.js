export function localeFor(woeid) {
  if (JA_WOEIDS.has(woeid)) return "ja";
  if (woeid === 1) return "global";
  return "en";
}

function slotOf(jstHour) {
  if (jstHour >= 5 && jstHour < 9) return "morning";
  if (jstHour >= 9 && jstHour < 15) return "daytime";
  if (jstHour >= 15 && jstHour < 19) return "evening";
  if (jstHour >= 19) return "night";
  return "latenight";
}

function hash32(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 指定時刻のデモトレンド（Python 側の fetch_demo と同じ3層スコアリング） */
export function demoTrends(woeid, ts = Math.floor(Date.now() / 1000), count = 50) {
  const bucket = ts - (ts % 300);
  const day = Math.floor(ts / 86400);
  const gRnd = mulberry32(hash32(`global|${bucket}`));
  const gDay = mulberry32(hash32(`global|day|${day}`));
  const lRnd = mulberry32(hash32(`locale|${woeid}|${bucket}`));
  const lDay = mulberry32(hash32(`locale|${woeid}|day|${day}`));
  const tRnd = mulberry32(hash32(`town|${woeid}|${bucket}`));
  const tDay = mulberry32(hash32(`town|${woeid}|day|${day}`));

  const locale = localeFor(woeid);
  const local = POOLS[locale] || EN;
  const isWorld = woeid === 1;
  const [gW, lW, tW] = isWorld ? [1.0, 0.0, 0.15] : [0.42, 0.62, 0.28];

  const jstHour = (new Date(ts * 1000).getUTCHours() + 9) % 24;
  const slot = slotOf(jstHour);
  const dow = new Date(ts * 1000).getUTCDay();
  const weekend = dow === 0 || dow === 6;
  const SLOTS = ["morning", "daytime", "evening", "night", "latenight"];

  function score(name, base, rnd, dayRnd, weight) {
    let v = base * weight * (0.55 + rnd() * 1.35);
    if (SLOTS[hash32(name) % 5] === slot) v *= 2.4 + rnd() * 3.6;
    if (dayRnd() < 0.0026) v *= 3 + rnd() * 6;
    if (weekend && hash32(name + "w") % 3 === 0) v *= 1.6;
    return v;
  }

  const seen = new Set();
  const scored = [];
  for (const [name, cat, base] of GLOBAL) {
    if (seen.has(name)) continue;
    seen.add(name);
    scored.push({ name, cat, v: score(name, base, gRnd, gDay, gW) });
  }
  for (const [name, cat, base] of local) {
    if (seen.has(name)) continue;
    seen.add(name);
    scored.push({
      name, cat,
      v: score(name, base, lRnd, lDay, lW) + score(name, base, tRnd, tDay, tW),
    });
  }

  scored.sort((a, b) => b.v - a.v);
  const top = scored.slice(0, count);
  const max = top.length ? top[0].v : 1;
  return top.map((t, i) => {
    const ratio = t.v / max;
    return {
      name: t.name,
      rank: i + 1,
      tweet_count: hash32(t.name) % 23 === 0
        ? null
        : Math.max(300, Math.round(Math.pow(ratio, 1.6) * (180000 + tRnd() * 340000))),
      category: t.cat,
      category_meta: CATS[t.cat] ? { id: t.cat, ...CATS[t.cat] } : { id: "other", ...CATS.other },
    };
  });
}
